use std::fs;
use std::path::Path;
use std::process::Command;
use anyhow::Result;

fn main() -> Result<()> {
    println!("🔍 QA SYSTEM: Validating generator completeness");
    
    // Test each instance generator
    validate_instance("002", "step2_bootstrap")?;
    validate_instance("003", "step3_bootstrap")?;
    validate_instance("004", "step4_bootstrap")?;
    validate_instance("005", "step5_bootstrap")?;
    validate_instance("006", "step6_bootstrap")?;
    
    println!("✅ QA COMPLETE: All generators validated");
    Ok(())
}

fn validate_instance(instance_num: &str, generator_name: &str) -> Result<()> {
    println!("\n🔍 VALIDATING INSTANCE {}", instance_num);
    
    let instance_path = format!("instances/{}", instance_num);
    let test_path = format!("qa_test_{}", instance_num);
    
    // Step 1: Check git commits for manual changes
    check_manual_changes(&instance_path)?;
    
    // Step 2: Delete existing test instance
    if Path::new(&test_path).exists() {
        fs::remove_dir_all(&test_path)?;
    }
    
    // Step 3: Regenerate using generator
    println!("🔄 Regenerating with generator: {}", generator_name);
    let output = Command::new("cargo")
        .args(&["run", "--bin", generator_name])
        .output()?;
    
    if !output.status.success() {
        anyhow::bail!("Generator {} failed", generator_name);
    }
    
    // Step 4: Compare generated vs original
    compare_instances(&instance_path, &test_path)?;
    
    // Step 5: Test generated instance
    test_generated_instance(&test_path)?;
    
    // Step 6: Clean up test instance
    fs::remove_dir_all(&test_path)?;
    
    println!("✅ INSTANCE {} VALIDATED: Completely generated by {}", instance_num, generator_name);
    Ok(())
}

fn check_manual_changes(instance_path: &str) -> Result<()> {
    println!("📋 Checking git commits for manual changes...");
    
    let output = Command::new("git")
        .args(&["log", "--oneline", "--", instance_path])
        .current_dir(instance_path)
        .output()?;
    
    let commits = String::from_utf8_lossy(&output.stdout);
    
    // Look for manual fix commits
    let manual_indicators = ["fix", "manual", "update", "correct", "patch"];
    let mut manual_changes = Vec::new();
    
    for line in commits.lines() {
        for indicator in &manual_indicators {
            if line.to_lowercase().contains(indicator) {
                manual_changes.push(line);
                break;
            }
        }
    }
    
    if !manual_changes.is_empty() {
        println!("⚠️  Manual changes detected:");
        for change in &manual_changes {
            println!("   {}", change);
        }
        println!("🔧 These changes need to be incorporated into the generator");
    } else {
        println!("✅ No manual changes detected");
    }
    
    Ok(())
}

fn compare_instances(original: &str, generated: &str) -> Result<()> {
    println!("🔍 Comparing original vs generated...");
    
    // Compare key files
    let key_files = ["build.rs", "Cargo.toml", "src/lib.rs"];
    
    for file in &key_files {
        let original_file = format!("{}/{}", original, file);
        let generated_file = format!("{}/{}", generated, file);
        
        if Path::new(&original_file).exists() && Path::new(&generated_file).exists() {
            let original_content = fs::read_to_string(&original_file)?;
            let generated_content = fs::read_to_string(&generated_file)?;
            
            if original_content != generated_content {
                println!("❌ DIFFERENCE in {}", file);
                println!("   Original: {} bytes", original_content.len());
                println!("   Generated: {} bytes", generated_content.len());
                
                // Show first difference
                let diff_pos = original_content.chars()
                    .zip(generated_content.chars())
                    .position(|(a, b)| a != b);
                
                if let Some(pos) = diff_pos {
                    println!("   First difference at position: {}", pos);
                }
            } else {
                println!("✅ {} matches perfectly", file);
            }
        }
    }
    
    Ok(())
}

fn test_generated_instance(test_path: &str) -> Result<()> {
    println!("🧪 Testing generated instance...");
    
    // Build test
    let build = Command::new("cargo")
        .args(&["build"])
        .current_dir(test_path)
        .status()?;
    
    if !build.success() {
        anyhow::bail!("Generated instance failed to build");
    }
    
    // Run test if test_universe exists
    let test_bin = format!("{}/src/bin/test_universe.rs", test_path);
    if Path::new(&test_bin).exists() {
        let test = Command::new("cargo")
            .args(&["run", "--bin", "test_universe"])
            .current_dir(test_path)
            .status()?;
        
        if !test.success() {
            anyhow::bail!("Generated instance test failed");
        }
        
        println!("✅ Generated instance builds and runs successfully");
    } else {
        println!("✅ Generated instance builds successfully");
    }
    
    Ok(())
}
