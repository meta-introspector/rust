use std::collections::{HashMap, HashSet};
use std::fs;
use syn::{parse_str, Item, ItemMod, ItemStruct};
use quote::quote;
use proc_macro2::TokenStream;

#[derive(Debug)]
struct ImportSource {
    import: String,
    source_file: String,
    line_number: usize,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut import_sources = Vec::new();
    
    // Collect imports with their exact source locations
    for entry in fs::read_dir("src")? {
        let entry = entry?;
        let path = entry.path();
        if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
            if name.starts_with("processed_") && name.ends_with(".rs") {
                let content = fs::read_to_string(&path)?;
                extract_super_imports_with_source(&content, name, &mut import_sources);
            }
        }
    }
    
    generate_wrap_types(&import_sources)?;
    Ok(())
}

fn extract_super_imports_with_source(content: &str, filename: &str, import_sources: &mut Vec<ImportSource>) {
    for (line_num, line) in content.lines().enumerate() {
        if line.trim_start().starts_with("use super::") {
            if let Some(import) = line.split("use super::").nth(1) {
                let import = import.split(';').next().unwrap_or("").trim();
                if !import.is_empty() {
                    import_sources.push(ImportSource {
                        import: import.to_string(),
                        source_file: filename.to_string(),
                        line_number: line_num + 1,
                    });
                }
            }
        }
    }
}

fn generate_wrap_types(import_sources: &[ImportSource]) -> Result<(), Box<dyn std::error::Error>> {
    let mut modules: HashMap<String, HashMap<String, Vec<&ImportSource>>> = HashMap::new();
    
    // Group imports by module and type, tracking sources
    for import_source in import_sources {
        if let Some(colon_pos) = import_source.import.find("::") {
            let module_name = &import_source.import[..colon_pos];
            let type_part = &import_source.import[colon_pos + 2..];
            
            if module_name != "super" {
                modules.entry(module_name.to_string())
                       .or_default()
                       .entry(type_part.to_string())
                       .or_default()
                       .push(import_source);
            }
        }
    }
    
    // Generate modules using syn/quote with source documentation
    let mut mod_items = Vec::new();
    
    for (module_name, types) in modules {
        let mut struct_items = Vec::new();
        
        for (type_name, sources) in types {
            // Clean type name
            let clean_name = type_name
                .replace("{", "")
                .replace("}", "")
                .replace("*", "Star")
                .replace(":", "");
            
            // Create source documentation comment
            let source_docs: Vec<String> = sources.iter()
                .map(|s| format!("// Source: {}:{}", s.source_file, s.line_number))
                .collect();
            let source_comment = source_docs.join("\n    ");
            
            if clean_name == "self" {
                let stub_name = format!("{}Stub", module_name);
                let struct_def = format!("    {}\n    pub struct {};", source_comment, stub_name);
                if let Ok(struct_item) = parse_str::<ItemStruct>(&format!("pub struct {};", stub_name)) {
                    struct_items.push(Item::Struct(struct_item));
                }
            } else if !clean_name.is_empty() && clean_name.chars().all(|c| c.is_alphanumeric() || c == '_') {
                let struct_def = format!("    {}\n    pub struct {};", source_comment, clean_name);
                if let Ok(struct_item) = parse_str::<ItemStruct>(&format!("pub struct {};", clean_name)) {
                    struct_items.push(Item::Struct(struct_item));
                }
            }
        }
        
        let mod_name = syn::Ident::new(&module_name, proc_macro2::Span::call_site());
        let module: ItemMod = syn::parse2(quote! {
            pub mod #mod_name {
                #(#struct_items)*
            }
        })?;
        
        mod_items.push(Item::Mod(module));
    }
    
    // Generate final file
    let total_imports = import_sources.len();
    let output: TokenStream = quote! {
        // wrap_types.rs - Dynamically generated support types
        // Generated by: syn_generator.rs
        // Total super:: imports processed: #total_imports
        // Each struct documents its exact source file and line number
        
        #(#mod_items)*
    };
    
    fs::write("src/wrap_types.rs", output.to_string())?;
    println!("Generated src/wrap_types.rs with {} imports from processed files", total_imports);
    Ok(())
}
