// batch_genmocks.rs - Generate merged module declarations and complete skeleton
use std::fs;
use std::collections::{HashMap, HashSet};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("🔄 Batch generating mocks and skeleton from all processed files...");
    
    let mut module_interfaces: HashMap<String, HashSet<String>> = HashMap::new();
    let mut file_modules: HashMap<String, String> = HashMap::new(); // processed_file -> module_path
    let mut processed_count = 0;
    
    // Scan all processed files
    for entry in fs::read_dir("src")? {
        let entry = entry?;
        let path = entry.path();
        if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
            if name.starts_with("temp_processed_") && name.ends_with(".rs") {
                analyze_file(&path, &mut module_interfaces, &mut file_modules)?;
                processed_count += 1;
            }
        }
    }
    
    println!("📊 Analyzed {} processed files", processed_count);
    println!("📋 Found {} unique modules: {:?}", module_interfaces.len(), module_interfaces.keys().collect::<Vec<_>>());
    
    // Generate declaration files
    for (module_name, _interfaces) in &module_interfaces {
        generate_module_decl_file(module_name)?;
    }
    
    // Generate complete skeleton
    generate_complete_skeleton(&file_modules, &module_interfaces)?;
    
    println!("✅ Generated {} module declaration files + complete skeleton", module_interfaces.len());
    Ok(())
}

fn analyze_file(path: &std::path::Path, module_interfaces: &mut HashMap<String, HashSet<String>>, file_modules: &mut HashMap<String, String>) -> Result<(), Box<dyn std::error::Error>> {
    let content = fs::read_to_string(path)?;
    let filename = path.file_name().and_then(|n| n.to_str()).unwrap_or("unknown");
    
    // Extract original source path
    if let Some(src_line) = content.lines().next() {
        if src_line.starts_with("// SRC: ") {
            let src_path = src_line.strip_prefix("// SRC: ").unwrap_or("");
            let module_path = source_to_module_path(src_path);
            file_modules.insert(filename.to_string(), module_path);
        }
    }
    
    // Find required modules
    for line in content.lines() {
        if line.trim().starts_with("use super::") {
            if let Some(module) = extract_module_name(line) {
                module_interfaces.entry(module).or_insert_with(HashSet::new);
            }
        }
    }
    
    Ok(())
}

fn source_to_module_path(src_path: &str) -> String {
    let path = src_path
        .strip_prefix("../rust/library/").unwrap_or(
        src_path.strip_prefix("../rust/compiler/").unwrap_or(src_path))
        .strip_suffix(".rs").unwrap_or(src_path)
        .replace("/src/", "::")
        .replace("/", "::");
    path
}

fn generate_complete_skeleton(file_modules: &HashMap<String, String>, module_interfaces: &HashMap<String, HashSet<String>>) -> Result<(), Box<dyn std::error::Error>> {
    let mut skeleton = String::new();
    skeleton.push_str("// Generated complete module skeleton\n");
    skeleton.push_str("// Auto-generated by batch_genmocks\n\n");
    
    // Generate alloc module with btree structure
    skeleton.push_str("pub mod alloc {\n");
    skeleton.push_str("    pub mod collections {\n");
    skeleton.push_str("        pub mod btree {\n");
    
    // Include module declarations first
    for module_name in module_interfaces.keys() {
        skeleton.push_str(&format!("            pub mod {} {{\n", module_name));
        skeleton.push_str(&format!("                include!(\"generated_{}_decl.rs\");\n", module_name));
        skeleton.push_str("            }\n");
    }
    
    // Include processed files in their proper modules
    for (processed_file, module_path) in file_modules {
        if module_path.contains("btree") {
            let module_name = module_path.split("::").last().unwrap_or("unknown");
            skeleton.push_str(&format!("            pub mod {} {{\n", module_name));
            skeleton.push_str(&format!("                include!(\"{}\");\n", processed_file));
            skeleton.push_str("            }\n");
        }
    }
    
    skeleton.push_str("        }\n");
    skeleton.push_str("    }\n");
    skeleton.push_str("}\n");
    
    // Add other top-level modules
    for module_name in module_interfaces.keys() {
        if !["merge_iter", "node"].contains(&module_name.as_str()) {
            skeleton.push_str(&format!("\npub mod {} {{\n", module_name));
            skeleton.push_str(&format!("    include!(\"generated_{}_decl.rs\");\n", module_name));
            skeleton.push_str("}\n");
        }
    }
    
    fs::write("src/generated_complete_skeleton.rs", skeleton)?;
    println!("📄 Generated src/generated_complete_skeleton.rs");
    
    Ok(())
}

fn extract_module_name(line: &str) -> Option<String> {
    if let Some(start) = line.find("super::") {
        let after_super = &line[start + 7..];
        if let Some(end) = after_super.find("::").or_else(|| after_super.find(";")) {
            return Some(after_super[..end].to_string());
        }
    }
    None
}

fn generate_module_decl_file(module_name: &str) -> Result<(), Box<dyn std::error::Error>> {
    let filename = format!("src/generated_{}_decl.rs", module_name);
    
    let source_path = match module_name {
        "merge_iter" => "../rust/library/alloc/src/collections/btree/merge_iter.rs",
        "node" => "../rust/library/alloc/src/collections/btree/node.rs", 
        "utils" => "../rust/compiler/rustc_macros/src/diagnostics/utils.rs",
        _ => {
            let content = format!("// Generated declarations for {} module\npub struct {}Stub;\n", module_name, module_name);
            fs::write(&filename, content)?;
            println!("📄 Generated {}", filename);
            return Ok(());
        }
    };
    
    if let Ok(source_content) = fs::read_to_string(source_path) {
        let mut decl_content = format!("// Generated declarations for {} module\n", module_name);
        decl_content.push_str("// Extracted from: ");
        decl_content.push_str(source_path);
        decl_content.push('\n');
        decl_content.push('\n');
        
        extract_declarations(&source_content, &mut decl_content);
        
        fs::write(&filename, decl_content)?;
        println!("📄 Generated {} from {}", filename, source_path);
    } else {
        let content = format!("// Generated declarations for {} module\n// Source not found: {}\npub struct {}Stub;\n", 
                             module_name, source_path, module_name);
        fs::write(&filename, content)?;
        println!("📄 Generated {} (stub only)", filename);
    }
    
    Ok(())
}

fn extract_declarations(content: &str, output: &mut String) {
    let mut brace_count: i32 = 0;
    let mut in_impl = false;
    let mut impl_buffer = String::new();
    
    for line in content.lines() {
        let trimmed = line.trim();
        
        // Skip empty lines and comments
        if trimmed.is_empty() || trimmed.starts_with("//") || trimmed.starts_with("#[") {
            continue;
        }
        
        // Extract standalone struct/enum/const declarations
        if (trimmed.starts_with("pub struct ") || 
            trimmed.starts_with("pub enum ") || 
            trimmed.starts_with("pub const ") ||
            trimmed.starts_with("struct ") ||
            trimmed.starts_with("enum ") ||
            trimmed.starts_with("const ")) && !in_impl {
            output.push_str(line);
            output.push('\n');
            continue;
        }
        
        // Handle impl blocks
        if trimmed.starts_with("impl") {
            in_impl = true;
            impl_buffer.clear();
            impl_buffer.push_str(line);
            impl_buffer.push('\n');
            brace_count = 0;
            
            // Count braces in this line
            for ch in line.chars() {
                match ch {
                    '{' => brace_count += 1,
                    '}' => brace_count = brace_count.saturating_sub(1),
                    _ => {}
                }
            }
            continue;
        }
        
        if in_impl {
            // Count braces
            for ch in line.chars() {
                match ch {
                    '{' => brace_count += 1,
                    '}' => brace_count = brace_count.saturating_sub(1),
                    _ => {}
                }
            }
            
            // Extract method signatures
            if (trimmed.starts_with("pub fn ") || trimmed.starts_with("fn ")) {
                let stub_method = create_method_stub(trimmed);
                impl_buffer.push_str("    ");
                impl_buffer.push_str(&stub_method);
                impl_buffer.push('\n');
            }
            
            // If we've closed all braces, end the impl block
            if brace_count == 0 {
                impl_buffer.push_str("}\n");
                output.push_str(&impl_buffer);
                in_impl = false;
            }
        }
    }
    
    // Handle unclosed impl block
    if in_impl {
        impl_buffer.push_str("}\n");
        output.push_str(&impl_buffer);
    }
}

fn create_method_stub(line: &str) -> String {
    if let Some(fn_start) = line.find("fn ") {
        let after_fn = &line[fn_start..];
        if let Some(brace_pos) = after_fn.find('{') {
            let signature = &after_fn[..brace_pos].trim();
            return format!("{} {{ unimplemented!() }}", signature);
        }
        if after_fn.contains(';') {
            return format!("{} {{ unimplemented!() }}", after_fn.trim_end_matches(';'));
        }
    }
    format!("// {}", line)
}
